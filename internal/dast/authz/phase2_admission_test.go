func p2Addr(t *testing.T, s string) netip.Addr {
	t.Helper()
	a, err := netip.ParseAddr(s)
	if err != nil {
		t.Fatalf("ParseAddr(%q): %v", s, err)
	}
	return a
}

// p2Target builds a Target directly, so that a test can present the gate stack
// with a combination the kernel's own construction path would never produce —
// which is exactly what a gate has to refuse.
func p2Target(t *testing.T, literal, canonical string, port uint16, addr string) Target {
	t.Helper()
	tgt, err := NewTarget(SchemeHTTPS, literal, canonical, port, p2Addr(t, addr))
	if err != nil {
		t.Fatalf("NewTarget(%q,%q,%d,%q): %v", literal, canonical, port, addr, err)
	}
	return tgt
}

// p2Scope builds a scope in the named mode with the given allow and deny
// entries, by rendering the scope file that describes them and loading it. The
// hash is whatever those bytes hash to; NewScope no longer accepts one.
func p2Scope(t *testing.T, mode Mode, allow, deny []ScopeEntry) Scope {
	t.Helper()
	decl, err := DeclareMode(mode)
	if err != nil {
		t.Fatalf("DeclareMode(%q): %v", mode, err)
	}
	s, err := NewScope(scopeFileJSON(mode, allow, deny), decl)
	if err != nil {
		t.Fatalf("NewScope: %v", err)
	}
	return s
}

// p2ExternalScope is the ordinary external-mode scope: one host, one port.
func p2ExternalScope(t *testing.T) Scope {
	t.Helper()
	return p2Scope(t, ModeExternal,
		[]ScopeEntry{{Host: "target.example.com", Ports: []uint16{443}}}, nil)
}

// p2StaticLookup returns a resolver that always answers with the same
// addresses and counts how many times it was called.
func p2StaticLookup(t *testing.T, calls *int, addrs ...string) lookupFunc {
	t.Helper()
	parsed := make([]netip.Addr, 0, len(addrs))
	for _, a := range addrs {
		parsed = append(parsed, p2Addr(t, a))
	}
	return func(context.Context, string) ([]netip.Addr, error) {
		if calls != nil {
			*calls++
		}
		return append([]netip.Addr(nil), parsed...), nil
	}
}

// p2AssertRefused is the shared shape of a GateResult refusal assertion.
func p2AssertRefused(t *testing.T, res GateResult, wantGate GateID, wantReason Reason) {
	t.Helper()
	if res.Passed() {
		t.Fatalf("the gate PASSED; it was required to refuse (%s / %s)", wantGate, wantReason)
	}
	if res.Gate() != wantGate {
		t.Fatalf("refusal attributed to %s; want %s (%s)", res.Gate(), wantGate, res.Err())
	}
	if got := res.Failure().Reason; got != wantReason {
		t.Fatalf("reason %q; want %q (%s)", string(got), string(wantReason), res.Err())
	}
	if !errors.Is(res.Err(), ErrRefused) {
		t.Fatalf("the failure does not unwrap to ErrRefused: %v", res.Err())
	}
}

// p2AssertRuled is the same for a Ruling from a chain gate.
func p2AssertRuled(t *testing.T, r Ruling, wantGate GateID, wantReason Reason) {
	t.Helper()
	if r.Permits() {
		t.Fatalf("the gate PERMITTED; it was required to refuse (%s / %s): %s",
			wantGate, wantReason, r)
	}
	if !r.WellFormedDenial() {
		t.Fatalf("the ruling is neither a well-formed permit nor a well-formed denial: %s", r)
	}
	if r.Gate() != wantGate {
		t.Fatalf("refusal attributed to %s; want %s: %s", r.Gate(), wantGate, r)
	}
	if r.Reason() != wantReason {
		t.Fatalf("reason %q; want %q: %s", string(r.Reason()), string(wantReason), r)
	}
}

