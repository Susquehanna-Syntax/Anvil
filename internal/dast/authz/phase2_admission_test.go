// TestCanonicalizeRefusalsAreDistinctlyAttributed.
//
// Every refusal Canonicalize makes carries a *GateFailure with its own
// gate08.slug token. Five of those branches would be caught by the general
// charset and length checks if they were deleted, so a test that asserted only
// "this is refused" would stay green with any of them gone -- what is lost is
// the ATTRIBUTION, and attribution is what reaches gate 21's audit log, since
// the offending host itself never can (the spine's record section: untrusted input).
//
// This is therefore the test that holds those branches. It also proves the
// token is recoverable through errors.As, which is how gate8Canonicalize and
// PinTarget report the specific failure rather than a generic one.
func TestCanonicalizeRefusalsAreDistinctlyAttributed(t *testing.T) {
	cases := []struct {
		in   string
		want Reason
	}{
		{"", ReasonHostEmpty},
		{".", ReasonHostEmpty},
		{strings.Repeat("a", 600), ReasonHostTooLong},
		{strings.Repeat("ab.", 90) + "example.com", ReasonHostTooLong},
		{"%zz.example.com", ReasonHostPercentEncoding},
		{"example.com%", ReasonHostPercentEncoding},
		{"%2577ww.example.com", ReasonHostDoublePercent},
		{"exämple.com", ReasonHostNotASCII},
		{"ex。ample.com", ReasonHostNotASCII},
		{"[::1", ReasonHostBracketMalformed},
		{"[not-an-address]", ReasonHostBracketMalformed},
		{"[::1]", ReasonHostIPv6Literal},
		{"[fe80::1]", ReasonHostIPv6Literal},
		{"a..b.example.com", ReasonHostLabel},
		{strings.Repeat("a", 64) + ".com", ReasonHostLabel},
		{"-lead.example.com", ReasonHostLabel},
		{"user@example.com", ReasonHostCharset},
		{"example.com:8080", ReasonHostCharset},
		{"*.example.com", ReasonHostCharset},
		{"0177.0.0.1", ReasonHostNumericTLD},
		{"2130706433", ReasonHostNumericTLD},
	}
	seen := map[Reason]bool{}
	for _, c := range cases {
		_, err := Canonicalize(c.in)
		if err == nil {
			t.Errorf("Canonicalize(%.24q) was accepted", c.in)
			continue
		}
		if !errors.Is(err, ErrRefused) {
			t.Errorf("Canonicalize(%.24q): the refusal does not unwrap to ErrRefused: %v",
				c.in, err)
		}
		var gf *GateFailure
		if !errors.As(err, &gf) {
			t.Errorf("Canonicalize(%.24q) returned an untyped error (%v); the specific "+
				"failure has to survive as a token, because the offending host cannot "+
				"be put in the audit row", c.in, err)
			continue
		}
		if gf.Gate != Gate8Canonicalize {
			t.Errorf("Canonicalize(%.24q) refused under %s", c.in, gf.Gate)
		}
		if gf.Reason != c.want {
			t.Errorf("Canonicalize(%.24q) refused with %q; want %q. Deleting the branch "+
				"that produces this token leaves the input refused by a later check and "+
				"loses the attribution, which is the whole thing the branch is for",
				c.in, string(gf.Reason), string(c.want))
		}
		if got := gate8ReasonOf(err); got != c.want {
			t.Errorf("gate8ReasonOf recovered %q for %.24q; want %q",
				string(got), c.in, string(c.want))
		}
		seen[c.want] = true
	}

	// Every gate-08 host token this file declares must be reachable. A token
	// nobody emits is an audit vocabulary that names nothing.
	for _, r := range []Reason{
		ReasonHostEmpty, ReasonHostTooLong, ReasonHostPercentEncoding,
		ReasonHostDoublePercent, ReasonHostNotASCII, ReasonHostBracketMalformed,
		ReasonHostIPv6Literal, ReasonHostCharset, ReasonHostLabel, ReasonHostNumericTLD,
	} {
		if !seen[r] {
			t.Errorf("no input in this table produces %q, so nothing demonstrates that "+
				"the token is ever emitted", string(r))
		}
	}

	// The fallback is fail-closed: an error this package did not mint still
	// yields a valid gate-8 token, so the audit row stays writable.
	if got := gate8ReasonOf(errors.New("something else")); got != ReasonCanonicalizeFailed {
		t.Errorf("gate8ReasonOf(foreign error) = %q; want %q",
			string(got), string(ReasonCanonicalizeFailed))
	}
	if got := gate8ReasonOf(nil); got != ReasonCanonicalizeFailed {
		t.Errorf("gate8ReasonOf(nil) = %q; want %q",
			string(got), string(ReasonCanonicalizeFailed))
	}
}

