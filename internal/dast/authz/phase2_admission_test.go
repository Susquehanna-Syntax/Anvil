// TestReservedDenylistCannotBeMutatedOrShortened is the "compiled constant,
// not a config key" assertion, made executable.
func TestReservedDenylistCannotBeMutatedOrShortened(t *testing.T) {
	// 1. The list is rebuilt on every call, so a caller that mutates what it
	//    was handed changes nothing. A package-level var would not have this
	//    property.
	first := reservedRanges()
	if len(first) == 0 {
		t.Fatal("the reserved-range denylist is empty")
	}
	first[0] = reservedRange{prefix: netip.MustParsePrefix("203.0.113.0/24"), why: "mutated"}
	second := reservedRanges()
	if second[0].prefix.String() == "203.0.113.0/24" {
		t.Fatal("mutating the slice reservedRanges() returned changed the denylist. It must " +
			"hand out a fresh slice, or a caller — including a future gate implementation " +
			"in this package — can shorten it at run time")
	}
	if _, reserved := AddressIsReserved(p2Addr(t, "127.0.0.1")); !reserved {
		t.Fatal("loopback stopped being reserved after the returned slice was mutated")
	}

	// 2. The exact set. This is a fixture, hand-written from research/20 gate
	//    10 plus this file's documented additions, so DELETING an entry fails
	//    here rather than silently widening what external mode may reach.
	want := map[string]bool{
		"0.0.0.0/8": true, "10.0.0.0/8": true, "100.64.0.0/10": true,
		"127.0.0.0/8": true, "169.254.0.0/16": true, "172.16.0.0/12": true,
		"192.0.0.0/24": true, "192.168.0.0/16": true, "198.18.0.0/15": true,
		"224.0.0.0/4": true, "240.0.0.0/4": true,
		"::/128": true, "::1/128": true, "64:ff9b::/96": true, "64:ff9b:1::/48": true,
		"2002::/16": true, "fc00::/7": true, "fe80::/10": true, "ff00::/8": true,
	}
	got := map[string]bool{}
	for _, r := range reservedRanges() {
		got[r.prefix.String()] = true
		if r.why == "" {
			t.Errorf("%s carries no explanation; a denylist whose entries cannot explain "+
				"themselves becomes a list nobody dares to shorten", r.prefix)
		}
	}
	for p := range want {
		if !got[p] {
			t.Errorf("%s is no longer in the reserved-range denylist", p)
		}
	}
	for p := range got {
		if !want[p] {
			t.Errorf("%s was added to the reserved-range denylist without being added to "+
				"this fixture. Adding is safe (it only ever refuses more) but it must be "+
				"deliberate", p)
		}
	}

	// 3. Nothing in the gate-10 path takes configuration. Stated by
	//    reflection over the signatures rather than by assertion in prose.
	if n := reflect.TypeOf(reservedRanges).NumIn(); n != 0 {
		t.Errorf("reservedRanges takes %d parameter(s); a denylist that takes an argument "+
			"is a denylist a caller can influence", n)
	}
	ait := reflect.TypeOf(AddressIsReserved)
	if ait.NumIn() != 1 || ait.In(0) != reflect.TypeOf(netip.Addr{}) {
		t.Errorf("AddressIsReserved's signature is %s; it must take an address and nothing "+
			"else, so there is no parameter through which the list could be overridden", ait)
	}
}

