func TestPhase2ZeroValuesAuthorizeNothing(t *testing.T) {
	if (RobotsPolicy{}).Determined() {
		t.Error("the zero RobotsPolicy reports Determined() == true, so a policy nobody " +
			"fetched would be acted on")
	}
	if (RobotsPolicy{}).PermitsPath("/") {
		t.Error("the zero RobotsPolicy permits a path")
	}
	if (RobotsPolicy{}).Determination() != RobotsUnset {
		t.Error("the zero RobotsPolicy does not report RobotsUnset")
	}
	if (SecurityTxtResult{}).Status() != SecurityTxtStatusUnset {
		t.Error("the zero SecurityTxtResult does not report SecurityTxtStatusUnset")
	}
	if len((SecurityTxtResult{}).Contacts()) != 0 {
		t.Error("the zero SecurityTxtResult carries a reporting contact")
	}
	if (SecurityTxtResult{}).AuditReason() != ReasonSecurityTxtUnread {
		t.Error("the zero SecurityTxtResult does not audit as unread")
	}
	if _, reserved := AddressIsReserved(netip.Addr{}); !reserved {
		t.Error("the zero netip.Addr is reported as NOT reserved, so an unset address would " +
			"read as routable")
	}
	if RobotsUnset != "" || SecurityTxtStatusUnset != "" || SecurityTxtLocationUnset != "" {
		t.Error("a Phase 2 enum's zero value is not the empty string, so a missing field " +
			"could decode as a real state")
	}
	// Every gateFunc this file registers must refuse four zero values.
	for _, g := range []GateID{Gate8Canonicalize, Gate9ResolveAndPin, Gate10ReservedRanges} {
		fn, ok := registry[g]
		if !ok || fn == nil {
			t.Fatalf("%s has no implementation compiled in", g)
		}
		if fn(Target{}, Scope{}, Attestation{}, Clock{}).Permits() {
			t.Errorf("%s permitted four zero-value inputs", g)
		}
	}
	// Gate 11's standalone form, on zero values.
	if CheckGate11RobotsDeny(RobotsPolicy{}, Target{}, "").Passed() {
		t.Error("CheckGate11RobotsDeny passed a zero policy, a zero target and an empty path")
	}
}

// TestPhase2BoundsAreCompiledConstantsWithNoConfigPath.
//
// plan/design/dynamic-tier.md marks every Phase 2 gate "no" in the Configurable column, and
// the standing instruction is that no such gate may be disabled by an
// environment variable, CLI flag, config key, or model-authored value. Phase 2
// has no Cap at all -- there is nothing here that "may only be lowered",
// because nothing here may be moved in either direction -- so the assertion is
// twofold: the values are what they were written as, and no exported entry
// point takes an argument through which one could be changed.
func TestPhase2BoundsAreCompiledConstantsWithNoConfigPath(t *testing.T) {
	bounds := []struct {
		name string
		got  int
		want int
	}{
		{"maxRawHostBytes", maxRawHostBytes, 512},
		{"maxCanonicalHostBytes", maxCanonicalHostBytes, 253},
		{"maxDNSLabelBytes", maxDNSLabelBytes, 63},
		{"maxResolvedAddresses", maxResolvedAddresses, 16},
		{"maxRobotsBytes", maxRobotsBytes, 64 * 1024},
		{"maxRobotsRules", maxRobotsRules, 1024},
		{"maxRobotsPatternBytes", maxRobotsPatternBytes, 512},
		{"maxRequestPathBytes", maxRequestPathBytes, 4096},
		{"maxSecurityTxtBytes", maxSecurityTxtBytes, 16 * 1024},
		{"maxSecurityTxtLines", maxSecurityTxtLines, 512},
		{"maxSecurityTxtValues", maxSecurityTxtValues, 32},
		{"maxSecurityTxtValueBytes", maxSecurityTxtValueBytes, 512},
	}
	for _, b := range bounds {
		if b.got != b.want {
			t.Errorf("%s is %d; this fixture says %d. Changing a Phase 2 bound is a "+
				"deliberate act and this test is where it is noticed", b.name, b.got, b.want)
		}
	}

	// Every exported Phase 2 entry point, and the shape of its inputs. None of
	// them takes a bound, a limit, a policy object or an options struct -- the
	// only values that cross these boundaries are the ones the gate is about.
	sigs := []struct {
		name string
		fn   any
		in   int
	}{
		{"Canonicalize", Canonicalize, 1},
		{"NormalizePort", NormalizePort, 2},
		{"DefaultPortFor", DefaultPortFor, 1},
		{"ResolveAndPin", ResolveAndPin, 3},
		{"PinTarget", PinTarget, 5},
		{"PinnedDialAddress", PinnedDialAddress, 2},
		{"AddressIsReserved", AddressIsReserved, 1},
		{"CheckGate11RobotsDeny", CheckGate11RobotsDeny, 3},
		{"FetchSecurityTxt", FetchSecurityTxt, 2},
	}
	intType := reflect.TypeOf(0)
	for _, c := range sigs {
		typ := reflect.TypeOf(c.fn)
		if typ.NumIn() != c.in {
			t.Errorf("%s takes %d parameters; this fixture says %d. A widened signature "+
				"is how a bound acquires a config path", c.name, typ.NumIn(), c.in)
			continue
		}
		for i := 0; i < typ.NumIn(); i++ {
			if typ.In(i) == intType {
				t.Errorf("%s parameter %d is a bare int. Every bound in Phase 2 is a "+
					"compiled-in const; an int parameter is the shape a limit takes "+
					"when it becomes configurable", c.name, i)
			}
		}
	}

	// And the resolver seam is unexported, so nothing outside this package can
	// supply one. lookupFunc appears in no exported signature.
	for _, c := range sigs {
		typ := reflect.TypeOf(c.fn)
		for i := 0; i < typ.NumIn(); i++ {
			if typ.In(i) == reflect.TypeOf(lookupFunc(nil)) {
				t.Errorf("%s takes a lookupFunc. Gate 9 requires the KERNEL to resolve; "+
					"a caller-supplied resolver is a caller-supplied answer", c.name)
			}
		}
	}
}

