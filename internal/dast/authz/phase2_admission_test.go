// TestCanonicalizeCaseFolds is the first primitive: DNS is case-insensitive
// and a scope entry is a string.
func TestCanonicalizeCaseFolds(t *testing.T) {
	for _, in := range []string{
		"EXAMPLE.COM",
		"Example.Com",
		"eXaMpLe.cOm",
		"WWW.EXAMPLE.COM",
	} {
		want := strings.ToLower(in)
		got, err := Canonicalize(in)
		if err != nil {
			t.Fatalf("Canonicalize(%q): %v", in, err)
		}
		if got != want {
			t.Fatalf("Canonicalize(%q) = %q; want %q", in, got, want)
		}
	}
}

// TestCanonicalizeStripsTheTrailingDot is the second primitive: "example.com."
// is the fully-qualified spelling of the same host and a different string.
func TestCanonicalizeStripsTheTrailingDot(t *testing.T) {
	got, err := Canonicalize("target.example.com.")
	if err != nil {
		t.Fatalf("Canonicalize: %v", err)
	}
	if got != "target.example.com" {
		t.Fatalf("Canonicalize(%q) = %q; want %q",
			"target.example.com.", got, "target.example.com")
	}
	// Exactly one dot is stripped. Two trailing dots is an empty label and is
	// not the same host.
	if _, err := Canonicalize("target.example.com.."); err == nil {
		t.Fatal("Canonicalize accepted a host with an empty final label; stripping every " +
			"trailing dot would make \"example.com..\" match \"example.com\"")
	}
}

// TestCanonicalizePercentDecodesExactlyOnce is the third primitive, and the
// one with a trap in it: a decoder that loops until its input stops changing
// can always be given one more layer.
func TestCanonicalizePercentDecodesExactlyOnce(t *testing.T) {
	ok := []struct{ in, want string }{
		{"%77ww.example.com", "www.example.com"},
		{"www%2eexample%2ecom", "www.example.com"},
		{"%57%57%57.example.com", "www.example.com"},
	}
	for _, c := range ok {
		got, err := Canonicalize(c.in)
		if err != nil {
			t.Fatalf("Canonicalize(%q): %v", c.in, err)
		}
		if got != c.want {
			t.Fatalf("Canonicalize(%q) = %q; want %q", c.in, got, c.want)
		}
	}

	// Double-encoded. One round of decoding leaves a '%', and a second round
	// is exactly what this refuses.
	for _, in := range []string{
		"%2577ww.example.com",
		"www%252eexample%252ecom",
		"%25",
	} {
		if got, err := Canonicalize(in); err == nil {
			t.Fatalf("Canonicalize(%q) = %q with no error; a doubly percent-encoded host "+
				"must be refused rather than decoded twice", in, got)
		}
	}

	// Malformed escapes.
	for _, in := range []string{"%zz.example.com", "www.example.com%", "%2.example.com"} {
		if _, err := Canonicalize(in); err == nil {
			t.Fatalf("Canonicalize(%q) accepted a malformed percent-escape", in)
		}
	}
}

// TestCanonicalizeRefusesNonASCIIAndAcceptsALabels is the IDNA primitive.
//
// This build refuses a U-label rather than mapping it (see Canonicalize's doc
// comment on why IDNA is not implemented inside the kernel), and passes an
// A-label through unchanged.
func TestCanonicalizeRefusesNonASCIIAndAcceptsALabels(t *testing.T) {
	refused := []struct{ in, why string }{
		{"exämple.com", "a U-label with a Latin-1 supplement character"},
		{"ex。ample.com", "U+3002 IDEOGRAPHIC FULL STOP, which IDNA maps to '.'"},
		{"ｅxample.com", "U+FF45 FULLWIDTH LATIN SMALL LETTER E"},
		{"exa​mple.com", "U+200B ZERO WIDTH SPACE, which IDNA maps away entirely"},
		{"аpple.com", "U+0430 CYRILLIC SMALL LETTER A — a homograph of 'a'"},
	}
	for _, c := range refused {
		if got, err := Canonicalize(c.in); err == nil {
			t.Fatalf("Canonicalize accepted %s and produced %q. Without IDNA in the kernel "+
				"there is no correct mapping, and passing the bytes through would let two "+
				"different names compare as one", c.why, got)
		}
	}
	// The A-label form of the same names is ASCII and passes through.
	for _, in := range []string{"xn--exmple-cua.com", "xn--80ak6aa92e.com"} {
		got, err := Canonicalize(in)
		if err != nil {
			t.Fatalf("Canonicalize(%q): %v — an A-label is already ASCII and is the form a "+
				"scope file has to contain", in, err)
		}
		if got != in {
			t.Fatalf("Canonicalize(%q) = %q; an A-label must pass through unchanged", in, got)
		}
	}
}

// TestCanonicalizeUnwrapsIPv4MappedIPv6 is the fifth primitive, and the one
// types.go names in NewTarget: "::ffff:169.254.169.254 and 169.254.169.254
// must not compare differently against gate 10's reserved ranges".
func TestCanonicalizeUnwrapsIPv4MappedIPv6(t *testing.T) {
	for _, in := range []string{
		"[::ffff:169.254.169.254]",
		"::ffff:169.254.169.254",
		"[::FFFF:169.254.169.254]",
	} {
		got, err := Canonicalize(in)
		if err != nil {
			t.Fatalf("Canonicalize(%q): %v", in, err)
		}
		if got != p2MetadataAddr {
			t.Fatalf("Canonicalize(%q) = %q; want %q — an IPv4-mapped IPv6 literal must "+
				"unwrap so that gate 10 sees the address it actually is", in, got, p2MetadataAddr)
		}
	}
	// A plain IPv4 literal canonicalizes to itself.
	got, err := Canonicalize(p2PublicAddr)
	if err != nil {
		t.Fatalf("Canonicalize(%q): %v", p2PublicAddr, err)
	}
	if got != p2PublicAddr {
		t.Fatalf("Canonicalize(%q) = %q", p2PublicAddr, got)
	}
	// Any other IPv6 literal is refused, because the kernel core's Target cannot carry a
	// canonical host containing ':'.
	for _, in := range []string{"[::1]", "[fe80::1]", "[2001:db8::1]", "::1"} {
		if _, err := Canonicalize(in); err == nil {
			t.Fatalf("Canonicalize accepted the IPv6 literal %q; NewTarget rejects a "+
				"canonical host containing %q, so it could not be carried anyway", in, ":")
		}
	}
	// Unbalanced brackets, and brackets around something that is not an
	// address.
	for _, in := range []string{"[::1", "::1]", "[]", "[not-an-address]", "[example.com]"} {
		if _, err := Canonicalize(in); err == nil {
			t.Fatalf("Canonicalize accepted %q", in)
		}
	}
}

