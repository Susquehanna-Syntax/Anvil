// p2Paths is the fixed probe set every robots test measures reach with. It is
// hand-written, not derived from any policy.
var p2Paths = []string{
	"/", "/index.html", "/public", "/public/a", "/admin", "/admin/", "/admin/users",
	"/api/v1/items", "/private.php", "/search?q=1", "/.git/config",
}

// p2Reach returns the subset of p2Paths a policy leaves in scope.
func p2Reach(t *testing.T, policy RobotsPolicy) []string {
	t.Helper()
	var out []string
	tgt := p2RobotsTarget(t)
	for _, p := range p2Paths {
		if CheckGate11RobotsDeny(policy, tgt, p).Passed() {
			out = append(out, p)
		}
	}
	return out
}

// TestGate11PermissiveRobotsGrantsZeroAdditionalReach is the gate's defining
// property. plan/design/dynamic-tier.md gate 11: "Restrictive robots.txt removes paths
// from scope; permissive adds nothing. No — asymmetric by design."
//
// The measurement is a set comparison, not a spot check: the set of paths
// reachable under a maximally permissive robots.txt must be EXACTLY the set
// reachable when there is no robots.txt at all. Not a superset. Identical.
func TestGate11PermissiveRobotsGrantsZeroAdditionalReach(t *testing.T) {
	absent := p2Reach(t, RobotsNotFound("target.example.com", 443))
	if len(absent) != len(p2Paths) {
		t.Fatalf("with no robots.txt, %d of %d probe paths are reachable; robots.txt is the "+
			"only thing under test here and its absence must remove nothing",
			len(absent), len(p2Paths))
	}

	permissive := []struct{ name, body string }{
		{"allow everything explicitly", "User-agent: *\nAllow: /\nDisallow:\n"},
		{"allow the paths a restrictive file would remove",
			"User-agent: *\nAllow: /admin\nAllow: /.git/\nAllow: /private.php\n"},
		{"a group naming Anvil that allows everything",
			"User-agent: anvil\nAllow: /\nDisallow:\n"},
		{"empty file", "\n\n# nothing here\n"},
		{"crawl-delay and sitemap only",
			"User-agent: *\nCrawl-delay: 0\nSitemap: https://target.example.com/sitemap.xml\n"},
	}
	for _, c := range permissive {
		t.Run(c.name, func(t *testing.T) {
			got := p2Reach(t, ParseRobotsTxt("target.example.com", 443, []byte(c.body)))
			if len(got) != len(absent) {
				t.Fatalf("a permissive robots.txt made %d paths reachable and no robots.txt "+
					"makes %d reachable. A permissive robots.txt must add NOTHING",
					len(got), len(absent))
			}
			for i := range got {
				if got[i] != absent[i] {
					t.Fatalf("reach differs at %d: %q vs %q", i, got[i], absent[i])
				}
			}
		})
	}
}

// TestGate11PermissiveGroupCannotUndoARestrictiveOne is the documented
// departure from RFC 9309 section 2.2.1's "most specific group wins".
func TestGate11PermissiveGroupCannotUndoARestrictiveOne(t *testing.T) {
	body := "User-agent: *\nDisallow: /\n\nUser-agent: anvil\nDisallow:\nAllow: /\n"
	policy := ParseRobotsTxt("target.example.com", 443, []byte(body))
	if !policy.HostFullyDenied() {
		t.Fatal("a group naming Anvil with an empty Disallow undid the \"*\" group's " +
			"Disallow: /. Under RFC 9309 that is correct and under gate 11 it is a " +
			"permissive statement ADDING reach, which the gate says cannot happen")
	}
	if got := p2Reach(t, policy); len(got) != 0 {
		t.Fatalf("%d paths remain reachable under a full-site Disallow: %v", len(got), got)
	}
}

