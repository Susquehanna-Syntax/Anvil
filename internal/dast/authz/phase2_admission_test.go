func TestParseRobotsTxtFailsClosed(t *testing.T) {
	// An oversized document and one carrying a byte outside printable ASCII
	// are both UNAVAILABLE — not absent, and not permissive.
	oversized := ParseRobotsTxt("target.example.com", 443,
		[]byte(strings.Repeat("a", maxRobotsBytes+1)))
	if oversized.Determination() != RobotsUnavailable {
		t.Fatalf("an oversized robots.txt produced determination %q",
			oversized.Determination())
	}
	binary := ParseRobotsTxt("target.example.com", 443,
		[]byte("User-agent: *\nDisallow: /a\x00b\n"))
	if binary.Determination() != RobotsUnavailable {
		t.Fatalf("a robots.txt containing a NUL produced determination %q",
			binary.Determination())
	}

	// A Disallow value this parser cannot interpret denies the whole host.
	// The conservative reading of an ununderstood deny is that it denies
	// everything; the alternative — ignoring it — is a deny that silently is
	// not there.
	weird := ParseRobotsTxt("target.example.com", 443,
		[]byte("User-agent: *\nDisallow: index.html\n"))
	if !weird.HostFullyDenied() {
		t.Fatal("a Disallow value that is neither empty nor a path was ignored. An " +
			"uninterpretable deny must deny more, not less")
	}

	// Rules before any User-agent line belong to no group and bind nobody
	// (RFC 9309 section 2.2.1) — but they must not therefore GRANT anything
	// either, so the reach is exactly the reach with no file.
	orphan := ParseRobotsTxt("target.example.com", 443, []byte("Disallow: /admin\n"))
	if len(orphan.DisallowedPatterns()) != 0 {
		t.Fatalf("a Disallow outside any group produced %d patterns",
			len(orphan.DisallowedPatterns()))
	}

	// An origin that cannot be named produces the zero policy, which permits
	// nothing.
	for _, bad := range []struct {
		host string
		port uint16
	}{
		{"", 443}, {"TARGET.example.com", 443}, {"target.example.com", 0},
		{"exämple.com", 443},
	} {
		p := ParseRobotsTxt(bad.host, bad.port, []byte("User-agent: *\nDisallow: /x\n"))
		if p.Determination() != RobotsUnset {
			t.Errorf("ParseRobotsTxt(%q,%d) produced determination %q; an origin that "+
				"cannot be named describes no policy", bad.host, bad.port, p.Determination())
		}
	}
}

