// TestDNSRebindingCannotReachThePinnedConnection is the fixture
// per-target admission's design asks for by name: "resolve returns scope-allowed IP,
// connect time re-resolve returns metadata IP — must use the pinned address".
//
// The resolver here is hostile: the first answer is routable and every answer
// after it is the cloud metadata endpoint. The assertion is not merely that
// the pinned address is the first one — it is that the resolver is called
// EXACTLY ONCE across pin, adjudication and dial-address construction, so
// there is no second answer for anything to use.
func TestDNSRebindingCannotReachThePinnedConnection(t *testing.T) {
	calls := 0
	hostile := func(context.Context, string) ([]netip.Addr, error) {
		calls++
		if calls == 1 {
			return []netip.Addr{p2Addr(t, p2PublicAddr)}, nil
		}
		return []netip.Addr{p2Addr(t, p2MetadataAddr)}, nil
	}

	tgt, res := pinTargetWith(context.Background(), hostile, SchemeHTTPS,
		"target.example.com", "443", ModeExternal)
	if !res.Passed() {
		t.Fatalf("pinning a routable answer refused: %v", res.Err())
	}
	if got := tgt.Pinned().String(); got != p2PublicAddr {
		t.Fatalf("pinned %s; the kernel resolved %s and must pin what it resolved",
			got, p2PublicAddr)
	}

	scope := p2ExternalScope(t)
	att := attestFor(t, scope)
	sink := &recordingSink{}
	d := adjudicateWith(sink, mustEnablement(t, scope, att), permitAll(admissionChain),
		tgt, scope, att, mustClock(t))
	if !d.Allowed() {
		t.Fatalf("the fixture decision did not allow, so the dial path cannot be exercised: %v",
			d.Err())
	}
	auth, err := d.Authorization()
	if err != nil {
		t.Fatalf("Authorization: %v", err)
	}

	ap, err := PinnedDialAddress(auth, tgt)
	if err != nil {
		t.Fatalf("PinnedDialAddress: %v", err)
	}
	if ap.Addr().String() != p2PublicAddr {
		t.Fatalf("the dial address is %s; the pinned address is %s. A second resolution "+
			"happened between the check and the connect, which is the DNS-rebinding TOCTOU "+
			"gate 9 exists to close", ap.Addr(), p2PublicAddr)
	}
	if calls != 1 {
		t.Fatalf("the resolver was called %d times between canonicalization and the dial "+
			"address. Gate 9 resolves ONCE; any second call is a window in which the "+
			"answer can change", calls)
	}
	if strings.Contains(ap.String(), "target.example.com") {
		t.Fatalf("the dial address %q contains a hostname. A dialer handed a name can "+
			"re-resolve it; the whole mechanism is that it is never given one", ap.String())
	}
	if ap.String() != p2PublicAddr+":443" {
		t.Fatalf("PinnedDialAddress = %q; want %q", ap.String(), p2PublicAddr+":443")
	}
}

