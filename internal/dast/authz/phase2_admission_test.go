// TestSecurityTxtIsUnreachableFromTheAdmissionDecision is
// per-target admission's design required evidence: "a compile-time or reflection-based
// test proving SecurityTxtResult is unreachable from Decide's argument types."
func TestSecurityTxtIsUnreachableFromTheAdmissionDecision(t *testing.T) {
	resultType := reflect.TypeOf(SecurityTxtResult{})
	docType := reflect.TypeOf(SecurityTxtDocument{})

	// 1. Both types satisfy the unexported marker interface, so the closure
	//    walk in kernel_test.go would reject them if they ever appeared. If
	//    this fails, every other assertion here is vacuous.
	iface := reflect.TypeOf((*excludedFromAdmission)(nil)).Elem()
	for _, typ := range []reflect.Type{resultType, docType} {
		if !typ.Implements(iface) {
			t.Fatalf("%s does not embed ReportingChannelOnly, so nothing detects it in the "+
				"admission input closure", typ)
		}
	}

	// 2. The transitive closure of every admission-facing signature. Decide,
	//    Adjudicate, Revalidate and gateFunc are all walked, because gate 12's
	//    requirement is about the decision's INPUT TYPE and any of the four
	//    would be a way in.
	banned := map[reflect.Type]string{
		resultType: "SecurityTxtResult",
		docType:    "SecurityTxtDocument",
	}
	seen := map[reflect.Type]bool{}
	var walk func(path string, typ reflect.Type)
	walk = func(path string, typ reflect.Type) {
		if typ == nil || seen[typ] {
			return
		}
		seen[typ] = true
		if name, bad := banned[typ]; bad {
			t.Errorf("%s reaches %s. The spine's safety section: security.txt resolves a reporting "+
				"channel and never grants permission, and the exclusion is enforced at the "+
				"type level rather than by convention", path, name)
			return
		}
		if typ.Implements(iface) || reflect.PointerTo(typ).Implements(iface) {
			t.Errorf("%s (%s) embeds ReportingChannelOnly and is reachable from an "+
				"admission signature", path, typ)
			return
		}
		if pkg := typ.PkgPath(); pkg != "" && !strings.HasPrefix(pkg, modulePath) {
			return
		}
		switch typ.Kind() {
		case reflect.Struct:
			for i := 0; i < typ.NumField(); i++ {
				f := typ.Field(i)
				walk(path+"."+f.Name, f.Type)
			}
		case reflect.Slice, reflect.Array, reflect.Pointer:
			walk(path+"[]", typ.Elem())
		case reflect.Map:
			walk(path+"{key}", typ.Key())
			walk(path+"{val}", typ.Elem())
		}
	}
	sigs := map[string]reflect.Type{
		"Decide":     reflect.TypeOf(Decide),
		"Revalidate": reflect.TypeOf(Revalidate),
		"Adjudicate": reflect.TypeOf(Adjudicate),
		"gateFunc":   reflect.TypeOf(gateFunc(nil)),
	}
	for name, fn := range sigs {
		for i := 0; i < fn.NumIn(); i++ {
			walk(fmt.Sprintf("%s.in[%d](%s)", name, i, fn.In(i)), fn.In(i))
		}
	}

	// 3. Positive control. The walk has to be able to fail, or its silence
	//    means nothing. A synthetic input type carrying the result must be
	//    detected.
	control := reflect.TypeOf(struct {
		Target Target
		Leak   SecurityTxtResult
	}{})
	found := false
	var probe func(reflect.Type) bool
	probe = func(typ reflect.Type) bool {
		if typ == resultType {
			return true
		}
		if typ.Kind() != reflect.Struct {
			return false
		}
		for i := 0; i < typ.NumField(); i++ {
			if probe(typ.Field(i).Type) {
				return true
			}
		}
		return false
	}
	found = probe(control)
	if !found {
		t.Fatal("the reachability probe cannot find SecurityTxtResult even when it is a " +
			"direct field, so the walk above proves nothing")
	}

	// 4. And gate 12 cannot be registered as a gate at all.
	m := map[GateID]gateFunc{}
	err := registerInto(m, Gate12SecurityTxtReportingChannel,
		func(Target, Scope, Attestation, Clock) Ruling {
			return permit(Gate12SecurityTxtReportingChannel, "gate12.x", "")
		})
	if err == nil {
		t.Fatal("registerInto accepted a gate 12 implementation")
	}
	if !errors.Is(err, ErrRefused) {
		t.Fatalf("the refusal does not unwrap to ErrRefused: %v", err)
	}
}

