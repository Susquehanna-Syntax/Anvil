// TestGate8BoundsTheTargetLiteral is the kernel-types review's finding that Target.literal
// was unbounded and unvalidated while every gate can read it back through
// Target.Literal().
//
// The critic pushed a 40 KB security.txt body through NewTarget. That is closed
// at the constructor now — this is the exact payload, and it does not construct
// — and gate 8 refuses the largest literal the constructor WILL accept, so
// neither layer is the only one holding.
func TestGate8BoundsTheTargetLiteral(t *testing.T) {
	nl := string(byte(10)) // a newline, written without an escape
	body := "Contact: mailto:sec@example.com" + nl +
		"Policy: https://example.com/vdp" + nl + strings.Repeat("A", 40000)

	tgt, err := NewTarget(SchemeHTTPS, body, "target.example.com", 443, p2Addr(t, p2PublicAddr))
	if err == nil {
		t.Fatal("NewTarget accepted a 40 KB security.txt body as a host literal. Every " +
			"gateFunc can read it back with Target.Literal(), which makes an unbounded " +
			"literal a channel around gate 12's structural exclusion")
	}
	if tgt.Constructed() {
		t.Fatal("NewTarget refused and returned a constructed Target anyway")
	}
	if !errors.Is(err, ErrRefused) {
		t.Fatalf("the refusal does not unwrap to ErrRefused: %v", err)
	}
	t.Logf("the critic's 40 KB literal is refused at construction: %v", err)

	// THE LENGTH ON ITS OWN. The payload above is refused by the charset
	// allowlist as well — a security.txt body has spaces and slashes in it — so
	// deleting the length bound would leave that case green. This one is
	// entirely allowlisted bytes and is over the bound by length alone, so the
	// length check is the only thing that can refuse it.
	oversized := strings.Repeat("a", maxLiteralHostBytes+1)
	if i := indexNonLiteralHostByte(oversized); i >= 0 {
		t.Fatalf("premise: this fixture has a byte outside the allowlist at offset %d, so "+
			"it does not isolate the length bound", i)
	}
	if _, err := NewTarget(SchemeHTTPS, oversized, "target.example.com", 443,
		p2Addr(t, p2PublicAddr)); err == nil {
		t.Errorf("NewTarget accepted a %d-byte host literal made entirely of allowlisted "+
			"bytes. The coded bound is %d, and Target.Literal() is readable by every gate",
			len(oversized), maxLiteralHostBytes)
	}

	// The BYTES, not just the length: a literal short enough to construct but
	// carrying characters no host literal has is refused too.
	for _, bad := range []string{
		"Contact: mailto:sec@example.com",
		"target.example.com/../admin",
		"target.example.com" + nl + "X-Injected: 1",
		"target example com",
	} {
		if _, err := NewTarget(SchemeHTTPS, bad, "target.example.com", 443,
			p2Addr(t, p2PublicAddr)); err == nil {
			t.Errorf("NewTarget accepted %q as a host literal", bad)
		}
	}

	// And the longest literal the constructor accepts still does not get past
	// gate 8, so the constructor's bound is not the only thing holding.
	labels := make([]string, 9)
	for i := range labels {
		labels[i] = strings.Repeat("abcdefghij", 5) // 50 bytes, inside the DNS label limit
	}
	long := strings.Join(labels, ".") // 458 bytes: over the 253-byte DNS name limit
	tgt, err = NewTarget(SchemeHTTPS, long, "target.example.com", 443, p2Addr(t, p2PublicAddr))
	if err != nil {
		t.Fatalf("premise: a %d-byte allowlisted literal did not construct, so gate 8's "+
			"half of this test is unreachable: %v", len(long), err)
	}
	r := gate8Canonicalize(tgt, p2ExternalScope(t), Attestation{}, mustClock(t))
	p2AssertRuled(t, r, Gate8Canonicalize, ReasonHostTooLong)
}

